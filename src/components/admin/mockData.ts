const ALL_STATUSES: OrderStatus[] = [
  "pending",
  "in_process",
  "done_process",
  "in_delivery",
  "done_delivery",
  "in_debit",
  "done",
  "cancel",
];

function shiftOrderDate(raw: string, dayOffset: number): string {
  const match = /^(\d{2})-(\d{2})-(\d{4})T(.+)$/.exec(raw);
  if (!match) return raw;
  const [, dd, mm, yyyy, rest] = match;
  const base = new Date(Number(yyyy), Number(mm) - 1, Number(dd));
  base.setDate(base.getDate() + dayOffset);
  const pad = (n: number) => String(n).padStart(2, "0");
  return `${pad(base.getDate())}-${pad(base.getMonth() + 1)}-${base.getFullYear()}T${rest}`;
}

// Expand the ~29 real seed records into ~98 rows so pagination (50/100 per
// page) has something to demonstrate. Offsets are deterministic (keyed off
// the loop index, not Math.random()) so the mock data stays stable across
// server/client renders.
function generateOrders(seed: Order[], total: number): Order[] {
  const salers = Array.from(new Set(seed.map((order) => order.saleAccount)));
  const florists = Array.from(
    new Set(
      seed
        .map((order) => order.floristAccount)
        .filter((value): value is string => Boolean(value)),
    ),
  );

  return Array.from({ length: total }, (_, index) => {
    const base = seed[index % seed.length];
    const cycle = Math.floor(index / seed.length);
    if (cycle === 0) return base;

    const dayOffset = cycle * seed.length + index;
    return {
      ...base,
      orderCode: `${base.orderCode}-${cycle}`,
      deliveryDateStart: shiftOrderDate(base.deliveryDateStart, -dayOffset),
      deliveryDateEnd: shiftOrderDate(base.deliveryDateEnd, -dayOffset),
      status: ALL_STATUSES[index % ALL_STATUSES.length],
      saleAccount: salers[index % salers.length],
      floristAccount:
        florists.length > 0 ? florists[index % florists.length] : undefined,
    };
  });
}

